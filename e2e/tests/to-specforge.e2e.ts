import { spawn } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, test } from 'e2e';

const repo = join(import.meta.dirname, '..', '..');
const cli = join(repo, 'drafter', 'to_specforge.py');
const python = process.env.DELPHI_PYTHON ?? 'python3';
const inklingPath = '/content/inkling';

type SelfDistilled = { id: string; prompt: string; completion: string; output_ids: number[]; finish_reason: string; completion_tokens: number; model_path: string };

function record(id: string, completion: string, overrides: Partial<SelfDistilled> = {}): SelfDistilled {
  const prompt = `<|message_system|><|content_text|>Thinking effort level: 0.9<|end_message|><|message_user|><|content_text|>question ${id}<|end_message|>`;
  return { id, prompt, completion, output_ids: [...completion].map((c) => c.charCodeAt(0)), finish_reason: 'stop', completion_tokens: completion.length, model_path: inklingPath, ...overrides };
}

function convert(dir: string, records: SelfDistilled[], extra: string[] = []): Promise<{ code: number | null; stdout: string; stderr: string; out: string }> {
  const input = join(dir, 'records.jsonl');
  const out = join(dir, 'train.jsonl');
  writeFileSync(input, records.map((r) => JSON.stringify(r)).join('\n') + '\n');
  return new Promise((resolve, reject) => {
    const child = spawn(python, ['-I', cli, '--records', input, '--out', out, '--expect-model', inklingPath, ...extra], { stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (c) => (stdout += c));
    child.stderr.on('data', (c) => (stderr += c));
    child.on('error', reject);
    child.on('close', (code) => resolve({ code, stdout, stderr, out }));
  });
}

type Row = { id: string; text: string };

function readRows(file: string): Row[] {
  return readFileSync(file, 'utf8').trim().split('\n').map((l) => JSON.parse(l) as Row);
}

function rowOf(r: SelfDistilled): Row {
  return { id: r.id, text: r.prompt + r.completion };
}

async function inWorkspace(check: (dir: string) => Promise<void>): Promise<void> {
  const dir = mkdtempSync(join(tmpdir(), 'delphi-to-specforge-'));
  try {
    await check(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('to_specforge writes each record as its preformatted prompt followed by its completion, in input order', async () => {
  await inWorkspace(async (dir) => {
    const records = [record('a', '<|message_model|><|content_text|>alpha<|end_message|>'), record('b', '<|message_model|><|content_text|>beta é 字<|end_message|>')];
    const run = await convert(dir, records);
    expect(run.stderr).toBe('');
    expect(run.code).toBe(0);
    expect(readRows(run.out)).toEqual(records.map(rowOf));
    expect(run.stdout).toContain(`kept ${records.length} of ${records.length}`);
  });
});

test('to_specforge drops records whose completion is empty', async () => {
  await inWorkspace(async (dir) => {
    const kept = record('a', '<|message_model|><|content_text|>alpha<|end_message|>');
    const run = await convert(dir, [kept, record('empty', '')]);
    expect(run.code).toBe(0);
    expect(readRows(run.out)).toEqual([rowOf(kept)]);
    expect(run.stdout).toContain('kept 1 of 2');
  });
});

test('to_specforge keeps only the first record of a repeated id', async () => {
  await inWorkspace(async (dir) => {
    const first = record('a', '<|message_model|><|content_text|>first<|end_message|>');
    const run = await convert(dir, [first, record('a', '<|message_model|><|content_text|>second<|end_message|>')]);
    expect(run.code).toBe(0);
    expect(readRows(run.out)).toEqual([rowOf(first)]);
    expect(run.stdout).toContain('kept 1 of 2');
  });
});

test('to_specforge keeps completions cut off at the token limit because they are still the target tokens', async () => {
  await inWorkspace(async (dir) => {
    const cut = record('b', '<|message_model|><|content_thinking|>long thought cut', { finish_reason: 'length' });
    const run = await convert(dir, [cut]);
    expect(run.code).toBe(0);
    expect(readRows(run.out)).toEqual([rowOf(cut)]);
  });
});

test('to_specforge refuses records generated by a different model', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'delphi-to-specforge-'));
  try {
    const run = await convert(dir, [record('a', 'x'), record('b', 'y', { model_path: '/content/other-model' })]);
    expect(run.code).toBe(2);
    expect(run.stderr).toContain('/content/other-model');
    expect(run.stderr).toContain('b');
    expect(existsSync(run.out)).toBe(false);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});